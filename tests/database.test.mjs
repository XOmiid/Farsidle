import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const catalog = JSON.parse(
  await readFile(new URL('../data/catalog.json', import.meta.url), 'utf8'),
);
const uid = '00000000-0000-4000-8000-000000000001';
async function setup() {
  const db = await PGlite.create();
  await db.exec(
    `create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;create table public.profiles(id uuid primary key,username text unique,avatar jsonb,birth_date date,country text,leaderboard_restricted boolean default false);grant select,update on public.profiles to public;create table public.game_streaks(user_id uuid,game text,last_win_date_key text,current_streak integer,primary key(user_id,game));create table public.coin_transactions(id bigint generated by default as identity primary key,user_id uuid,amount integer,source text,date_key text,created_at timestamptz default clock_timestamp());create function public.award_coins(uuid,text,integer,text) returns void language sql security definer as $$select$$;insert into auth.users values('${uid}');insert into profiles(id,username,birth_date) values('${uid}','player_one','2000-01-01');`,
  );
  for (const file of [
    'classic-schema.sql',
    'classic-actions.sql',
    'classic-accounts.sql',
    'classic-compatibility.sql',
  ])
    await db.exec(await readFile(new URL('../supabase/' + file, import.meta.url), 'utf8'));
  await db.query('insert into classic_private.content(singleton,data)values(true,$1)', [catalog]);
  await db.exec('commit');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [uid]);
  return db;
}
async function rpc(db, name, args = []) {
  if (name === 'classic_act' && args[0] !== 'crossword' && args[1].round === undefined) {
    const state = await raw(db, args[0]);
    args[1] = { ...args[1], round: state.history.length, day: state.date };
  }
  return (
    await db.query(
      'select public.' + name + '(' + args.map((_, i) => '$' + (i + 1)).join(',') + ') as result',
      args,
    )
  ).rows[0].result;
}
async function raw(db, game) {
  return (
    await db.query(
      "select state from classic_private.games where user_id=auth.uid() and state->>'game'=$1 order by updated_at desc limit 1",
      [game],
    )
  ).rows[0].state;
}
async function age(db, game, index, ms) {
  await db.query(
    "update classic_private.games set state=jsonb_set(state,$2::text[],to_jsonb((extract(epoch from clock_timestamp())*1000-$3)::bigint)) where user_id=auth.uid() and state->>'game'=$1",
    [game, ['puzzle', 'startedAt', String(index)], ms],
  );
}
test('Supabase upgrade runs in isolated PostgreSQL and enforces access, rewards and all seven games', async (t) => {
  const db = await setup();
  try {
    await t.test('private tables and legacy award endpoint are inaccessible', async () => {
      await db.exec('set role anon');
      // Preserve the legacy site's existing read access during the additive rollout.
      await db.query('select id,username,avatar from public.profiles');
      await assert.rejects(db.query('select birth_date,country from public.profiles'));
      await assert.rejects(db.query('select * from classic_private.players'));
      await assert.rejects(rpc(db, 'award_coins', [uid, 'fake', 100000, 'today']));
      await assert.rejects(rpc(db, 'classic_profile'));
      await db.exec('reset role');
      await db.exec('set role authenticated');
      const p = await rpc(db, 'classic_profile');
      assert.equal(p.name, 'player_one');
      await assert.rejects(db.query('update classic_private.players set restricted=false'));
      await assert.rejects(db.query('update public.profiles set leaderboard_restricted=false'));
      await assert.rejects(db.query('select * from classic_private.prelaunch_backup'));
      await db.exec('reset role');
    });
    await t.test('daily claims cannot award twice', async () => {
      assert.equal(await rpc(db, 'classic_claim'), 25);
      assert.equal(await rpc(db, 'classic_claim'), 0);
      assert.equal((await rpc(db, 'classic_profile')).balance, 25);
    });
    await t.test('Wordle cannot fabricate a win or rewrite a completed score', async () => {
      const p = await rpc(db, 'classic_get', ['wordle', null]);
      assert.equal(p.secret, undefined);
      assert.equal(p.answer, undefined);
      await assert.rejects(rpc(db, 'classic_act', ['wordle', { type: 'guess', word: 'x' }, null]));
      const unlisted = 'ظ'.repeat(p.puzzle.length);
      assert(!catalog.words.includes(unlisted));
      const unlistedResult = await rpc(db, 'classic_act', [
        'wordle',
        { type: 'guess', word: unlisted },
        null,
      ]);
      assert.equal(unlistedResult.history[0].word, unlisted);
      assert.equal(unlistedResult.won, false);
      await assert.rejects(
        rpc(db, 'classic_act', [
          'wordle',
          { type: 'guess', word: 'x'.repeat(p.puzzle.length) },
          null,
        ]),
      );
      const answer = (await raw(db, 'wordle')).secret.word;
      const result = await rpc(db, 'classic_act', [
        'wordle',
        { type: 'guess', word: answer },
        null,
      ]);
      assert.equal(result.won, true);
      assert.equal(result.reward, 100);
      const before = (await rpc(db, 'classic_profile')).balance;
      await rpc(db, 'classic_act', ['wordle', { type: 'guess', word: answer }, null]);
      assert.equal((await rpc(db, 'classic_profile')).balance, before);
    });
    await t.test('Factle has five countries and server-scored rounds', async () => {
      await rpc(db, 'classic_get', ['factle', null]);
      let s = await raw(db, 'factle');
      assert.equal(new Set(s.secret.countries.map((c) => c.id)).size, 5);
      for (const c of s.secret.countries)
        s = await rpc(db, 'classic_act', ['factle', { type: 'guess', country: c.id }, null]);
      assert.equal(s.score, 5);
      assert.equal(s.reward, 100);
      assert.equal(s.finished, true);
    });
    await t.test('Colordle reveal timing persists and score is server computed', async () => {
      await rpc(db, 'classic_get', ['colordle', null]);
      const first = await rpc(db, 'classic_act', ['colordle', { type: 'reveal' }, null]);
      const again = await rpc(db, 'classic_act', ['colordle', { type: 'reveal' }, null]);
      assert.equal(first.puzzle.revealedAt, again.puzzle.revealedAt);
      await assert.rejects(
        rpc(db, 'classic_act', ['colordle', { type: 'color', rgb: [0, 0, 0] }, null]),
      );
      await db.query(
        "update classic_private.games set state=jsonb_set(state,'{puzzle,revealedAt}',to_jsonb((extract(epoch from clock_timestamp())*1000-11000)::bigint))where state->>'game'='colordle'",
      );
      const h = (await raw(db, 'colordle')).secret.color.hex;
      const channels = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
      const result = await rpc(db, 'classic_act', [
        'colordle',
        { type: 'color', rgb: channels },
        null,
      ]);
      assert.equal(result.score, 10);
    });
    await t.test('Memory rejects repeated answers and scores two distinct rounds', async () => {
      await rpc(db, 'classic_get', ['memorydle', null]);
      let s = await raw(db, 'memorydle');
      for (let i = 0; i < 2; i++) {
        await rpc(db, 'classic_act', ['memorydle', { type: 'start' }, null]);
        await age(db, 'memorydle', i, 13000);
        const targets = s.secret.levels[i].targets;
        await assert.rejects(
          rpc(db, 'classic_act', [
            'memorydle',
            { type: 'memory', picks: Array(5).fill(targets[0]) },
            null,
          ]),
        );
        await rpc(db, 'classic_act', ['memorydle', { type: 'memory', picks: targets }, null]);
      }
      s = await raw(db, 'memorydle');
      assert.equal(s.score, 10);
      assert.equal(s.finished, true);
    });
    await t.test('Chordle requires valid rounds and computes a 15-point result', async () => {
      await rpc(db, 'classic_get', ['chordle', null]);
      const s = await raw(db, 'chordle');
      let result;
      await assert.rejects(
        rpc(db, 'classic_act', ['chordle', { type: 'chords', slots: [99, 99, 99, 99, 99] }, null]),
      );
      for (const slots of s.secret.sequences)
        result = await rpc(db, 'classic_act', ['chordle', { type: 'chords', slots }, null]);
      assert.equal(result.score, 15);
      assert.equal(result.reward, 150);
    });
    await t.test('Teamdle choices belong to the requested country', async () => {
      const state = await rpc(db, 'classic_get', ['teamdle', null]);
      for (const round of state.puzzle.rounds) {
        const country = catalog.countries.find((c) => c.id === round.id);
        assert.deepEqual(new Set(round.choices), new Set([country.capital, country.otherCity]));
        assert.equal(new Set(round.choices).size, 2);
      }
    });
    await t.test('Teamdle deadlines and assignments cannot be supplied by the client', async () => {
      await rpc(db, 'classic_get', ['teamdle', null]);
      const s = await raw(db, 'teamdle');
      await rpc(db, 'classic_act', ['teamdle', { type: 'start' }, null]);
      await age(db, 'teamdle', 0, 7000);
      const result = await rpc(db, 'classic_act', [
        'teamdle',
        { type: 'capital', answer: s.secret.countries[0].capital, country: 'arbitrary' },
        null,
      ]);
      assert.equal(result.score, 0);
      assert.equal(result.history.length, 1);
      for (let i = 1; i < 4; i++) {
        await rpc(db, 'classic_act', ['teamdle', { type: 'start' }, null]);
        await rpc(db, 'classic_act', [
          'teamdle',
          { type: 'capital', answer: s.secret.countries[i].capital },
          null,
        ]);
      }
      assert.equal((await raw(db, 'teamdle')).score, 3);
    });
    await t.test('Crossword purchase is single-charge and solutions are hidden', async () => {
      const id = String(catalog.crosswords[0].id);
      const initial = await rpc(db, 'classic_get', ['crossword', id]);
      assert.equal(initial.puzzle.slots[0].word, undefined);
      await assert.rejects(
        rpc(db, 'classic_act', ['crossword', { type: 'letter', cell: '0_0', letter: 'ا' }, id]),
      );
      await db.query(
        "insert into classic_private.coins values($1,'fixture',1000,'fixture','2000-01-01',now())",
        [uid],
      );
      const before = (await rpc(db, 'classic_profile')).balance;
      await rpc(db, 'classic_act', ['crossword', { type: 'purchase' }, id]);
      await rpc(db, 'classic_act', ['crossword', { type: 'purchase' }, id]);
      assert.equal((await rpc(db, 'classic_profile')).balance, before - catalog.crosswords[0].cost);
      const state = await raw(db, 'crossword');
      const cells = (
        await db.query('select classic_private.cell_map($1) as cells', [state.secret.crossword])
      ).rows[0].cells;
      for (const [cell, letter] of Object.entries(cells))
        await rpc(db, 'classic_act', ['crossword', { type: 'letter', cell, letter }, id]);
      const solved = await rpc(db, 'classic_act', ['crossword', { type: 'check' }, id]);
      assert.equal(solved.finished, true);
    });
    await t.test('anonymous leaderboard output excludes private fields', async () => {
      await db.exec('set role anon');
      const rows = await rpc(db, 'classic_leaderboard', ['wordle']);
      assert.equal(rows.length, 1);
      assert.equal(rows[0].birth_date, undefined);
      assert.equal(rows[0].user_id, undefined);
      await db.exec('reset role');
    });

    await t.test(
      'ranking bonuses pay first, second, third and later places differently',
      async () => {
        for (const [n, reward] of [
          [2, 80],
          [3, 65],
          [4, 50],
        ]) {
          const id = '00000000-0000-4000-8000-00000000000' + n;
          await db.query('insert into auth.users values($1)', [id]);
          await db.query('insert into public.profiles(id,username)values($1,$2)', [
            id,
            'player_' + n,
          ]);
          await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
          await rpc(db, 'classic_get', ['wordle', null]);
          const answer = (await raw(db, 'wordle')).secret.word;
          const result = await rpc(db, 'classic_act', [
            'wordle',
            { type: 'guess', word: answer },
            null,
          ]);
          assert.equal(result.reward, reward);
        }
        await db.query("select set_config('request.jwt.claim.sub',$1,false)", [uid]);
      },
    );

    await t.test(
      'Wordle lists all winners by submission time before even an earlier loss',
      async () => {
        const loser = '00000000-0000-4000-8000-000000000005';
        await db.query('insert into auth.users values($1)', [loser]);
        await db.query('insert into public.profiles(id,username)values($1,$2)', [
          loser,
          'player_loss',
        ]);
        await db.query("select set_config('request.jwt.claim.sub',$1,false)", [loser]);
        const initial = await rpc(db, 'classic_get', ['wordle', null]);
        for (const letter of ['ا', 'ب', 'پ', 'ت', 'ث', 'ج'])
          await rpc(db, 'classic_act', [
            'wordle',
            { type: 'guess', word: letter.repeat(initial.puzzle.length) },
            null,
          ]);
        assert.equal((await raw(db, 'wordle')).won, false);
        for (const [n, seconds] of [
          [1, 20],
          [2, 40],
          [3, 10],
          [4, 30],
          [5, -60],
        ])
          await db.query(
            "update classic_private.games set updated_at=clock_timestamp()+($2::text||' seconds')::interval where user_id=$1 and state->>'game'='wordle'",
            ['00000000-0000-4000-8000-00000000000' + n, seconds],
          );
        const rows = await rpc(db, 'classic_leaderboard', ['wordle']);
        assert.deepEqual(
          rows.map((e) => e.name),
          ['player_3', 'player_one', 'player_4', 'player_2', 'player_loss'],
        );
        assert.deepEqual(
          rows.map((e) => e.won),
          [true, true, true, true, false],
        );
        assert(rows.every((e) => e.submittedAt));
        await db.query("select set_config('request.jwt.claim.sub',$1,false)", [uid]);
      },
    );
    await t.test('team leaderboard reports balanced totals from matched players', async () => {
      const id = '00000000-0000-4000-8000-000000000002';
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
      await rpc(db, 'classic_get', ['teamdle', null]);
      const s = await raw(db, 'teamdle');
      for (const country of s.secret.countries) {
        await rpc(db, 'classic_act', ['teamdle', { type: 'start' }, null]);
        await rpc(db, 'classic_act', [
          'teamdle',
          { type: 'capital', answer: country.capital },
          null,
        ]);
      }
      const result = await rpc(db, 'classic_leaderboard', ['teamdle']);
      assert.equal(result.totals.coral, 3);
      assert.equal(result.totals.blue, 4);
      assert.equal(result.entries.filter((e) => e.pending).length, 0);
      assert.deepEqual(
        result.entries.filter((e) => e.team === 'coral').map((e) => [e.name, e.score]),
        [['player_one', 3]],
      );
      assert.deepEqual(
        result.entries.filter((e) => e.team === 'blue').map((e) => [e.name, e.score]),
        [['player_2', 4]],
      );
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [uid]);
    });
    await t.test('team settlement pays only matched participants, once', async () => {
      const ids = [
        uid,
        '00000000-0000-4000-8000-000000000002',
        '00000000-0000-4000-8000-000000000003',
      ];
      const day = (await db.query('select (classic_private.game_day()::date-1)::text as day'))
        .rows[0].day;
      for (const [i, team, slot, score] of [
        [0, 'coral', 1, 4],
        [1, 'blue', 1, 2],
        [2, 'coral', 2, 4],
      ])
        await db.query('insert into classic_private.teams values($1,$2,$3,$4,$5)', [
          day,
          ids[i],
          team,
          slot,
          score,
        ]);
      await rpc(db, 'classic_profile');
      await rpc(db, 'classic_profile');
      const coins = (
        await db.query('select user_id,amount from classic_private.coins where event_key=$1', [
          'team:' + day,
        ])
      ).rows;
      assert.deepEqual(coins, [{ user_id: uid, amount: 150 }]);
    });
    await t.test('legacy and Classic coins stay synchronized without double counting', async () => {
      const before = (await rpc(db, 'classic_profile')).balance;
      const inserted = await db.query(
        "insert into public.coin_transactions(user_id,date_key,source,amount)values($1,classic_private.game_day(),'legacy_test',17) returning id",
        [uid],
      );
      assert.equal((await rpc(db, 'classic_profile')).balance, before + 17);
      await db.query('update public.coin_transactions set amount=19 where id=$1', [
        inserted.rows[0].id,
      ]);
      assert.equal((await rpc(db, 'classic_profile')).balance, before + 19);
      const balances = (
        await db.query(
          'select (select sum(amount) from public.coin_transactions where user_id=$1) as old,(select sum(amount) from classic_private.coins where user_id=$1) as classic',
          [uid],
        )
      ).rows[0];
      assert.equal(balances.old, balances.classic);
      await db.query('delete from public.coin_transactions where id=$1', [inserted.rows[0].id]);
      assert.equal((await rpc(db, 'classic_profile')).balance, before);
    });
    await t.test('profile edits and moderation changes remain synchronized', async () => {
      await rpc(db, 'classic_update_profile', ['player_updated', '◇']);
      assert.equal(
        (await db.query('select username from public.profiles where id=$1', [uid])).rows[0]
          .username,
        'player_updated',
      );
      await db.query(
        'update public.profiles set username=$2,leaderboard_restricted=true where id=$1',
        [uid, 'player_one'],
      );
      assert.equal((await rpc(db, 'classic_profile')).name, 'player_one');
      assert.equal(
        (await db.query('select restricted from classic_private.players where id=$1', [uid]))
          .rows[0].restricted,
        true,
      );
      await db.query('update public.profiles set leaderboard_restricted=false where id=$1', [uid]);
    });
    await t.test(
      'optional account details can be set and cleared and stay off leaderboards',
      async () => {
        await rpc(db, 'classic_update_profile', [
          'player_one',
          '◇',
          { birthDate: '1994-03-21', country: 'ایران' },
        ]);
        const saved = await rpc(db, 'classic_profile');
        assert.equal(saved.birthDate, '1994-03-21');
        assert.equal(saved.country, 'ایران');
        await rpc(db, 'classic_update_profile', ['player_one', '◇']);
        assert.equal((await rpc(db, 'classic_profile')).birthDate, '1994-03-21');
        await assert.rejects(
          rpc(db, 'classic_update_profile', [
            'player_one',
            '◇',
            { birthDate: '2999-01-01', country: 'ایران' },
          ]),
        );
        await db.exec('set role anon');
        const table = await rpc(db, 'classic_leaderboard', ['wordle']);
        assert(!JSON.stringify(table).includes('1994-03-21'));
        assert(!JSON.stringify(table).includes('birthDate'));
        await assert.rejects(rpc(db, 'classic_update_profile', ['player_one', '◇', {}]));
        await db.exec('reset role');
        await rpc(db, 'classic_update_profile', [
          'player_one',
          '◇',
          { birthDate: null, country: null },
        ]);
        assert.equal((await rpc(db, 'classic_profile')).birthDate, null);
        assert.equal((await rpc(db, 'classic_profile')).country, null);
      },
    );
    await t.test('the default crossword is the active mini, not a retired puzzle ID', async () => {
      const initial = await rpc(db, 'classic_get', ['crossword', null]);
      assert.equal(String(initial.puzzle.id), String(catalog.crosswords[0].id));
    });
    await t.test('a migrated daily claim cannot be paid a second time', async () => {
      const id = '00000000-0000-4000-8000-000000000002';
      await db.query(
        "insert into classic_private.coins(user_id,event_key,amount,source,day) values($1,'legacy:claim',25,'daily_login',classic_private.game_day())",
        [id],
      );
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
      assert.equal(await rpc(db, 'classic_claim'), 0);
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [uid]);
    });
  } finally {
    await db.close();
  }
});
